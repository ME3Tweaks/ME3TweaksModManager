using System.Text.Json;
using System.Text.Json.Serialization;

namespace ME3TweaksModManager.modmanager.milan.slash
{
    /// <summary>
    /// The signable portion of a Milan slash manifest. As with <see cref="MilanDeltaSignableBody"/>, properties are declared
    /// in the order the signature is computed over, and <see cref="MilanSlashManifest"/> extends this class so the
    /// signature is not part of the signed body.
    /// </summary>
    internal class MilanSlashSignableBody
    {
        [JsonPropertyName("milanslash")]
        public bool MilanSlash { get; set; }

        [JsonPropertyName("version")]
        public double Version { get; set; }

        /// <summary>
        /// TFCs to rebuild from ranges of existing TFCs.
        /// </summary>
        [JsonPropertyName("tfcs")]
        public List<MilanSlashTFCEntry> TFCs { get; set; } = new();

        /// <summary>
        /// Files to transform with a JPatch delta.
        /// </summary>
        [JsonPropertyName("patches")]
        public List<MilanSlashPatchEntry> Patches { get; set; } = new();

        /// <summary>
        /// Files to remove entirely once everything else has been built.
        /// </summary>
        [JsonPropertyName("deletions")]
        public List<MilanSlashDeletionEntry> Deletions { get; set; } = new();

        /// <summary>
        /// Size and hash of every file in the finished installation this manifest was generated from, recorded after
        /// everything the installer does (slash, TOC, bink bypass). Used to verify an end user's installation matches exactly.
        /// </summary>
        [JsonPropertyName("finalfiles")]
        public List<MilanSlashFinalFileEntry> FinalFiles { get; set; } = new();
    }

    /// <summary>
    /// Manifest describing how to 'slash' an installed Project Milan game down to only the data it actually uses. It is
    /// generated by development builds of Mod Manager against a freshly built base installation, and lives at
    /// MilanDelta/slash.json inside the Project Milan mod's folder. Every path is relative to the root of the game
    /// (for game files) or to the MilanDelta folder (for delta files).
    /// </summary>
    internal class MilanSlashManifest : MilanSlashSignableBody
    {
        [JsonPropertyName("signature")]
        public string Signature { get; set; }

        /// <summary>
        /// Computes the signature over the signable body. The same serialization must be used when generating and verifying.
        /// </summary>
        public string ComputeSignature()
        {
            var bodyJson = JsonSerializer.Serialize<MilanSlashSignableBody>(this);
            return MilanSlashHashing.HashBytes(System.Text.Encoding.UTF8.GetBytes(bodyJson));
        }

        /// <summary>
        /// Signs the manifest and writes it to the given MilanDelta folder.
        /// </summary>
        public void Save(string milanDeltaFolder)
        {
            Signature = ComputeSignature();
            Directory.CreateDirectory(milanDeltaFolder);
            File.WriteAllText(Path.Combine(milanDeltaFolder, MilanSlashApplier.SlashManifestFileName), JsonSerializer.Serialize(this, new JsonSerializerOptions { WriteIndented = true }));
        }
    }

    /// <summary>
    /// Describes a TFC that is assembled from byte ranges of one or more existing TFCs. The patch file only carries these
    /// offsets and lengths (plus the new TFC's GUID); all texture data comes from the TFCs already on disk.
    /// </summary>
    internal class MilanSlashTFCEntry
    {
        /// <summary>
        /// Output TFC, relative to the game root. May be a new file, or the same file as one of the sources.
        /// </summary>
        [JsonPropertyName("filename")]
        public string Filename { get; set; }

        /// <summary>
        /// GUID written as the TFC's 16 byte header. Textures that use this TFC reference it in their TFCFileGuid property.
        /// </summary>
        [JsonPropertyName("guid")]
        public Guid Guid { get; set; }

        /// <summary>
        /// TFCs that data is pulled from, relative to the game root.
        /// </summary>
        [JsonPropertyName("sources")]
        public List<MilanSlashSourceFile> Sources { get; set; } = new();

        /// <summary>
        /// Ranges to copy, in output order, after the GUID header.
        /// </summary>
        [JsonPropertyName("segments")]
        public List<MilanSlashTFCSegment> Segments { get; set; } = new();

        /// <summary>
        /// Size of the output, including the 16 byte GUID header.
        /// </summary>
        [JsonPropertyName("destsize")]
        public long DestSize { get; set; }

        [JsonPropertyName("desthash")]
        public string DestHash { get; set; }
    }

    internal class MilanSlashSourceFile
    {
        [JsonPropertyName("filename")]
        public string Filename { get; set; }

        /// <summary>
        /// Expected size of the file on disk. TFCs are too large to hash up front; the output hash catches bad data.
        /// </summary>
        [JsonPropertyName("size")]
        public long Size { get; set; }
    }

    /// <summary>
    /// A copy of <see cref="Length"/> bytes from <see cref="Offset"/> in source <see cref="SourceIndex"/>. Serialized as a
    /// compact [source, offset, length] array, as TFCs can have thousands of these.
    /// </summary>
    [JsonConverter(typeof(MilanSlashTFCSegmentConverter))]
    internal readonly record struct MilanSlashTFCSegment(int SourceIndex, long Offset, long Length);

    internal class MilanSlashTFCSegmentConverter : JsonConverter<MilanSlashTFCSegment>
    {
        public override MilanSlashTFCSegment Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)
        {
            if (reader.TokenType != JsonTokenType.StartArray)
                throw new JsonException(@"Expected [source, offset, length] array for TFC segment");

            var values = new long[3];
            for (int i = 0; i < 3; i++)
            {
                if (!reader.Read() || reader.TokenType != JsonTokenType.Number)
                    throw new JsonException(@"TFC segment must contain exactly 3 numbers");
                values[i] = reader.GetInt64();
            }

            if (!reader.Read() || reader.TokenType != JsonTokenType.EndArray)
                throw new JsonException(@"TFC segment must contain exactly 3 numbers");

            return new MilanSlashTFCSegment(checked((int)values[0]), values[1], values[2]);
        }

        public override void Write(Utf8JsonWriter writer, MilanSlashTFCSegment value, JsonSerializerOptions options)
        {
            // Raw so indented output keeps each segment on a single line
            writer.WriteRawValue($@"[{value.SourceIndex},{value.Offset},{value.Length}]", skipInputValidation: true);
        }
    }

    internal static class MilanSlashPatchModes
    {
        /// <summary>
        /// The delta applies to the LEC-decompressed package data (the same convention as MilanDelta), and the result is
        /// re-saved through LEC.
        /// </summary>
        public const string Package = @"package";

        /// <summary>
        /// The delta applies to the file's bytes as-is. Used for uncompressed files, such as the 1.3GB RefShaderCache,
        /// so they can be patched file-to-file without loading them into memory.
        /// </summary>
        public const string Raw = @"raw";
    }

    internal class MilanSlashPatchEntry
    {
        [JsonPropertyName("comment")]
        public string Comment { get; set; }

        /// <summary>
        /// File to patch, relative to the game root. The patched result replaces it.
        /// </summary>
        [JsonPropertyName("filename")]
        public string Filename { get; set; }

        /// <summary>
        /// JPatch delta file, relative to the MilanDelta folder.
        /// </summary>
        [JsonPropertyName("delta")]
        public string Delta { get; set; }

        /// <summary>
        /// One of <see cref="MilanSlashPatchModes"/>.
        /// </summary>
        [JsonPropertyName("mode")]
        public string Mode { get; set; }

        /// <summary>
        /// For package mode, if the result should be saved compressed.
        /// </summary>
        [JsonPropertyName("compressed")]
        public bool Compressed { get; set; }

        /// <summary>
        /// Size of the file on disk before patching. Checked before anything is modified.
        /// </summary>
        [JsonPropertyName("sourcefilesize")]
        public long SourceFileSize { get; set; }

        /// <summary>
        /// SHA-256 of the file on disk before patching. Checked before anything is modified.
        /// </summary>
        [JsonPropertyName("sourcefilehash")]
        public string SourceFileHash { get; set; }

        /// <summary>
        /// Size of the data the delta is applied to (decompressed package data in package mode, the file in raw mode).
        /// </summary>
        [JsonPropertyName("sourcesize")]
        public long SourceSize { get; set; }

        [JsonPropertyName("sourcehash")]
        public string SourceHash { get; set; }

        /// <summary>
        /// Size of the data the delta produces.
        /// </summary>
        [JsonPropertyName("destsize")]
        public long DestSize { get; set; }

        [JsonPropertyName("desthash")]
        public string DestHash { get; set; }
    }

    /// <summary>
    /// A file to delete once everything else has been built, such as a TFC whose used data has all been moved into other
    /// TFCs, or one nothing references.
    /// </summary>
    internal class MilanSlashDeletionEntry
    {
        /// <summary>
        /// Why the file is deleted.
        /// </summary>
        [JsonPropertyName("comment")]
        public string Comment { get; set; }

        [JsonPropertyName("filename")]
        public string Filename { get; set; }

        [JsonPropertyName("size")]
        public long Size { get; set; }
    }

    internal class MilanSlashFinalFileEntry
    {
        /// <summary>
        /// Path relative to the game root.
        /// </summary>
        [JsonPropertyName("filename")]
        public string Filename { get; set; }

        [JsonPropertyName("size")]
        public long Size { get; set; }

        [JsonPropertyName("hash")]
        public string Hash { get; set; }
    }
}
